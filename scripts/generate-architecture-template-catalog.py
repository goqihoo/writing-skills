#!/usr/bin/env python3
"""Validate shared architecture templates and render their Writer assignments."""
import argparse
import sys
from pathlib import Path
import yaml

ROOT = Path(__file__).resolve().parents[1]
SHARED = Path('methods/architecture-templates')


def architecture_templates(root=ROOT):
    directory = root / SHARED
    path = directory / 'templates.yaml'
    manifest = yaml.safe_load(path.read_text())
    if not isinstance(manifest, dict) or manifest.get('schema_version') != 1 or manifest.get('owner_method') != 'architecture-templates' or manifest.get('policy') != 'adaptive':
        raise ValueError('Invalid shared architecture template manifest')
    entries = manifest.get('templates')
    if not isinstance(entries, list) or not entries:
        raise ValueError('Architecture templates must be a nonempty list')
    ids, assets = set(), set()
    for entry in entries:
        if not isinstance(entry, dict) or any(not isinstance(entry.get(k), str) or not entry[k].strip() for k in ('id', 'name', 'group', 'reader_question', 'template')):
            raise ValueError('Every template needs identity, group, reader question and asset path')
        asset = (directory / entry['template']).resolve()
        if entry['id'] in ids or asset in assets:
            raise ValueError('Duplicate architecture template identity or asset')
        if not asset.is_file() or asset.parent != (directory / 'assets').resolve():
            raise ValueError(f'Invalid template asset: {asset}')
        ids.add(entry['id'])
        assets.add(asset)
    bundled = {p.resolve() for p in (directory / 'assets').glob('*.md')}
    if assets != bundled:
        raise ValueError('Bundled architecture templates differ from active manifest assets')
    return entries


def cell(value):
    return ' '.join(value.split()).replace('|', '\\|')


def render(root=ROOT):
    entries = architecture_templates(root)
    lines = ['# Architecture template catalog', '', 'Generated by `scripts/generate-architecture-template-catalog.py`. Edit the shared manifest, Writer assignments and assets, then regenerate.', '', '## Primary architecture templates', '', 'Purpose determines content development; document responsibility selects the template; four viewpoints guide reasoning and completeness. Architecture Knowledge and Concrete Design share these four files. Apply the Knowledge method or the [concrete-design profile](../methods/architecture-templates/concrete-design.md), preserving company/System versus Project authority. Select only the needed design granularities.', '', '| Template | Reader question |', '| --- | --- |']
    for e in entries:
        if e['group'] == 'Primary':
            asset = SHARED / e['template']
            lines.append(f"| [{cell(e['name'])}](../{asset.as_posix()}) | {cell(e['reader_question'])} |")
    lines += ['', '## Other existing resources', '', 'Retained specialist and navigation resources are outside the primary-template family. Use a governing assignment or an explicitly requested or established structure; these resources do not prescribe extra documents or viewpoint directories.', '', '| Group | Template | Reader question |', '| --- | --- | --- |']
    for e in entries:
        if e['group'] != 'Primary':
            asset = SHARED / e['template']
            lines.append(f"| {cell(e['group'])} | [{cell(e['name'])}](../{asset.as_posix()}) | {cell(e['reader_question'])} |")
    lines += ['', '## Writer assignments and specific supplements', '', 'Registered artifact identities and authority remain with their Writers. Shared file assignments do not create new Public Skills or mandatory documents.', '', '| Owner | Type | Template |', '| --- | --- | --- |']
    for owner in ('write-technical-architecture', 'write-technical-doc'):
        registry_path = root / 'skills' / owner / 'references/internal-document-types.yaml'
        reg = yaml.safe_load(registry_path.read_text())
        for e in reg['types']:
            if 'template' in e and (owner == 'write-technical-architecture' or e['id'] in ('system-architecture', 'subsystem-architecture', 'module-design', 'component-architecture', 'architecture-decision')):
                asset = (registry_path.parent / e['template']['path']).resolve()
                file = asset.name
                relative = asset.relative_to(root.resolve()).as_posix()
                lines.append(f"| `{owner}` | {cell(e['name'])} | [{file}](../{relative}) |")
    return '\n'.join(lines) + '\n'


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    try:
        output = render()
    except (ValueError, KeyError, OSError, yaml.YAMLError) as error:
        print(f'error: {error}', file=sys.stderr)
        return 1
    path = ROOT / 'docs/architecture-template-catalog.md'
    if args.check:
        if not path.exists() or path.read_text() != output:
            print('error: architecture template catalog is out of date', file=sys.stderr)
            return 1
    else:
        path.write_text(output)
    return 0


if __name__ == '__main__':
    sys.exit(main())
