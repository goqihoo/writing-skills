#!/usr/bin/env python3
"""Validate the Knowledge template manifest and render architecture asset links."""
import argparse
import sys
from pathlib import Path
import yaml

ROOT = Path(__file__).resolve().parents[1]
OWNER = 'write-architecture-knowledge'


def knowledge_templates(root=ROOT):
    skill = root / 'skills' / OWNER
    path = skill / 'references/architecture-templates.yaml'
    manifest = yaml.safe_load(path.read_text())
    if not isinstance(manifest, dict) or manifest.get('schema_version') != 1 or manifest.get('owner_skill') != OWNER or manifest.get('policy') != 'adaptive':
        raise ValueError('Invalid Architecture Knowledge template manifest')
    entries = manifest.get('templates')
    if not isinstance(entries, list) or not entries:
        raise ValueError('Knowledge templates must be a nonempty list')
    ids, assets = set(), set()
    for entry in entries:
        if not isinstance(entry, dict) or any(not isinstance(entry.get(k), str) or not entry[k].strip() for k in ('id', 'name', 'group', 'reader_question', 'template')):
            raise ValueError('Every template needs identity, group, reader question and asset path')
        asset = (path.parent / entry['template']).resolve()
        if entry['id'] in ids or asset in assets:
            raise ValueError('Duplicate Knowledge template identity or asset')
        if not asset.is_file() or asset.parent != (skill / 'assets').resolve():
            raise ValueError(f'Invalid template asset: {asset}')
        ids.add(entry['id'])
        assets.add(asset)
    bundled = {p.resolve() for p in (skill / 'assets').glob('*.md')}
    if assets != bundled:
        raise ValueError('Bundled Knowledge templates differ from active manifest assets')
    return entries


def cell(value):
    return ' '.join(value.split()).replace('|', '\\|')


def render(root=ROOT):
    lines = ['# Architecture template catalog', '', 'Generated by `scripts/generate-architecture-template-catalog.py`. Edit the owning manifests and assets, then regenerate.', '', '## Architecture Knowledge', '', '| Group | Template | Reader question |', '| --- | --- | --- |']
    for e in knowledge_templates(root):
        file = Path(e['template']).name
        lines.append(f"| {cell(e['group'])} | [{cell(e['name'])}](../skills/{OWNER}/assets/{file}) | {cell(e['reader_question'])} |")
    lines += ['', '## Concrete architecture and delivery', '', '| Owner | Type | Template |', '| --- | --- | --- |']
    for owner in ('write-technical-architecture', 'write-technical-doc'):
        reg = yaml.safe_load((root / 'skills' / owner / 'references/internal-document-types.yaml').read_text())
        for e in reg['types']:
            if 'template' in e and (owner == 'write-technical-architecture' or e['id'] in ('system-architecture', 'subsystem-architecture', 'component-architecture', 'architecture-decision')):
                file = Path(e['template']['path']).name
                lines.append(f"| `{owner}` | {cell(e['name'])} | [{file}](../skills/{owner}/assets/{file}) |")
    return '\n'.join(lines) + '\n'


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    try:
        output = render()
    except (ValueError, KeyError, OSError, yaml.YAMLError) as error:
        print(f'error: {error}', file=sys.stderr)
        return 1
    path = ROOT / 'docs/architecture-template-catalog.md'
    if args.check:
        if not path.exists() or path.read_text() != output:
            print('error: architecture template catalog is out of date', file=sys.stderr)
            return 1
    else:
        path.write_text(output)
    return 0


if __name__ == '__main__':
    sys.exit(main())
